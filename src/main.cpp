/**
 * @file main.cpp
 * @brief Точка входа программы: главное меню лабораторной работы №3.
 * @details Из главного меню пользователь выбирает номер задания.
 * Лабораторная работа выполняется поэтапно, и в каждой версии
 * программы добавляется новое задание:
 * - v0.1 — Задание №1 (…);
 * - v0.2 — Задание №2 (…);
 * - v1.0 — последнее задание, работа выполнена полностью.
 * @author Vareshka86
 * @date 2026-10-03
 * @version 0.1
 */

#include "input.h"
// #include "task1.h"   // подключить заголовок каждого готового задания

#include <iostream>
#include <stdexcept>

#ifdef _WIN32
#define WIN32_LEAN_AND_MEAN // подключать только основную часть WinAPI
#include <windows.h>        // SetConsoleOutputCP, SetConsoleCP
#endif

/// Текущая версия программы (совпадает с меткой версии в git).
constexpr const char* PROGRAM_VERSION = "v0.1";

/// Вспомогательные функции, видимые только внутри этого файла.
namespace
{

/**
 * @brief Настраивает консоль Windows на кодировку UTF-8.
 * @details Исходные файлы сохранены в UTF-8. Без этой настройки
 * русский текст в консоли Windows выводится «кракозябрами».
 * В Linux/macOS консоль уже работает в UTF-8, поэтому там функция
 * ничего не делает (код внутри `#ifdef _WIN32` не компилируется).
 */
void setupConsole()
{
#ifdef _WIN32
    SetConsoleOutputCP(CP_UTF8);
    SetConsoleCP(CP_UTF8);
#endif
}

/**
 * @brief Выводит главное меню программы.
 */
void printMainMenu()
{
    std::cout << "\n========================================\n"
              << " Лабораторная работа №3 по ООП (" << PROGRAM_VERSION << ")\n"
              << "========================================\n"
              << "  1 - Задание №1: … (в разработке)\n"
              << "  2 - Задание №2: … (в разработке)\n"
              << "  0 - выход\n";
}

} // namespace

/**
 * @brief Главная функция программы.
 * @details Показывает главное меню и запускает выбранное задание.
 * Исключения, возникшие при работе (например, закончился поток ввода),
 * перехватываются здесь, чтобы программа завершилась с понятным
 * сообщением, а не аварийно.
 * @return 0 — при нормальном завершении, 1 — при ошибке.
 */
int main()
{
    setupConsole();

    try
    {
        while (true)
        {
            printMainMenu();
            const int choice = readIntInRange("Ваш выбор: ", 0, 2);

            switch (choice)
            {
            case 1:
            case 2:
                std::cout << "Задание №" << choice
                          << " будет реализовано в следующей версии программы.\n";
                break;

            default: // 0 - выход
                std::cout << "Работа программы завершена.\n";
                return 0;
            }
        }
    }
    catch (const std::exception& error)
    {
        std::cerr << "\nОшибка: " << error.what() << '\n';
        return 1;
    }
}
