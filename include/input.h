/**
 * @file input.h
 * @brief Вспомогательные функции безопасного ввода чисел с клавиатуры.
 * @details Используются во всех заданиях лабораторной работы. Функции
 * защищают программу от некорректного ввода: если пользователь вводит
 * буквы, дробное число или «мусор» после числа, ввод повторяется,
 * а программа не зацикливается и не падает.
 * @author Vareshka86
 * @date 2026-10-03
 * @version 0.1
 */

#ifndef INPUT_H
#define INPUT_H

#include <string>

/**
 * @brief Считывает с клавиатуры одно целое число.
 * @details Читается вся строка целиком (std::getline), затем из неё
 * извлекается число. Ввод считается корректным, только если строка
 * содержит ровно одно целое число (пробелы по краям допускаются).
 * Например, «12», « -5 » — корректно; «abc», «12abc», «3.5» — нет.
 * При ошибке выводится сообщение и запрос повторяется.
 * @param prompt Текст приглашения, который выводится перед вводом.
 *               Передаётся по константной ссылке, чтобы не копировать строку.
 * @return Введённое пользователем целое число.
 * @exception std::runtime_error Если поток ввода закончился (например,
 *            нажато Ctrl+Z / Ctrl+D), и прочитать число больше невозможно.
 */
int readInt(const std::string& prompt);

/**
 * @brief Считывает целое число из диапазона [minValue; maxValue].
 * @details Повторяет запрос до тех пор, пока пользователь не введёт
 * число, попадающее в заданный диапазон (границы включаются).
 * @param prompt   Текст приглашения к вводу.
 * @param minValue Минимальное допустимое значение.
 * @param maxValue Максимальное допустимое значение.
 * @return Введённое число, гарантированно лежащее в диапазоне.
 * @exception std::runtime_error Если поток ввода закончился.
 * @warning Должно выполняться условие minValue <= maxValue.
 */
int readIntInRange(const std::string& prompt, int minValue, int maxValue);

/**
 * @brief Считывает с клавиатуры одно число с дробной частью (double).
 * @details Как и readInt(), читает всю строку и принимает её, только если в
 * ней ровно одно число. Дробную часть можно отделять точкой или запятой:
 * «2.5» и «2,5» — одно и то же. Бесконечность и «не число» не принимаются.
 * @param prompt Текст приглашения к вводу.
 * @return Введённое конечное число.
 * @exception std::runtime_error Если поток ввода закончился.
 */
double readDouble(const std::string& prompt);

#endif // INPUT_H
